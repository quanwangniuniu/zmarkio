-- Decision service schema ownership draft.
-- This migration mirrors the tables the .NET service reads/writes today.
-- It is intentionally idempotent so it can be introduced without dropping the
-- existing Django-created tables.

CREATE TABLE IF NOT EXISTS decisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    is_deleted boolean NOT NULL,
    title varchar(255),
    context_summary text,
    reasoning text,
    risk_level varchar(10),
    confidence integer,
    status varchar(20) NOT NULL,
    requires_approval boolean NOT NULL,
    planned_decision_date timestamptz,
    committed_at timestamptz,
    approved_at timestamptz,
    is_reference_case boolean NOT NULL,
    created_by_agent boolean NOT NULL,
    agent_session_id uuid,
    is_pre_draft boolean NOT NULL,
    project_seq integer NOT NULL,
    approved_by_id bigint REFERENCES core_customuser(id) DEFERRABLE INITIALLY DEFERRED,
    author_id bigint REFERENCES core_customuser(id) DEFERRABLE INITIALLY DEFERRED,
    committed_by_id bigint REFERENCES core_customuser(id) DEFERRABLE INITIALLY DEFERRED,
    last_edited_by_id bigint REFERENCES core_customuser(id) DEFERRABLE INITIALLY DEFERRED,
    project_id bigint REFERENCES core_project(id) DEFERRABLE INITIALLY DEFERRED,
    topic varchar(64) NOT NULL,
    slug varchar(255) NOT NULL,
    CONSTRAINT decisions_project_seq_check CHECK (project_seq >= 0),
    CONSTRAINT decisions_slug_key UNIQUE (slug),
    CONSTRAINT unique_project_decision_seq UNIQUE (project_id, project_seq)
);

CREATE INDEX IF NOT EXISTS decisions_project_status_idx
    ON decisions(project_id, status)
    WHERE is_deleted = false;

CREATE TABLE IF NOT EXISTS decision_options (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    is_deleted boolean NOT NULL,
    text text NOT NULL,
    is_selected boolean NOT NULL,
    "order" integer NOT NULL,
    decision_id bigint NOT NULL REFERENCES decisions(id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT decision_options_order_check CHECK ("order" >= 0)
);

CREATE INDEX IF NOT EXISTS decision_options_decision_idx
    ON decision_options(decision_id, "order")
    WHERE is_deleted = false;

CREATE TABLE IF NOT EXISTS decision_signals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    is_deleted boolean NOT NULL,
    metric varchar(30),
    movement varchar(30),
    period varchar(20),
    comparison varchar(30) NOT NULL,
    scope_type varchar(20),
    scope_value varchar(255),
    delta_value numeric(12, 2),
    delta_unit varchar(20),
    display_text text NOT NULL,
    display_text_override text,
    author_id bigint REFERENCES core_customuser(id) DEFERRABLE INITIALLY DEFERRED,
    decision_id bigint NOT NULL REFERENCES decisions(id) DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX IF NOT EXISTS decision_signals_decision_idx
    ON decision_signals(decision_id)
    WHERE is_deleted = false;

CREATE TABLE IF NOT EXISTS decision_edges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    is_deleted boolean NOT NULL,
    created_by_id bigint REFERENCES core_customuser(id) DEFERRABLE INITIALLY DEFERRED,
    from_decision_id bigint NOT NULL REFERENCES decisions(id) DEFERRABLE INITIALLY DEFERRED,
    to_decision_id bigint NOT NULL REFERENCES decisions(id) DEFERRABLE INITIALLY DEFERRED,
    edge_type varchar(32) NOT NULL,
    CONSTRAINT decision_edge_no_self_loop CHECK (NOT (from_decision_id = to_decision_id)),
    CONSTRAINT unique_decision_edge UNIQUE (from_decision_id, to_decision_id)
);

CREATE TABLE IF NOT EXISTS decision_reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    is_deleted boolean NOT NULL,
    outcome_text text NOT NULL,
    reflection_text text NOT NULL,
    quality varchar(20) NOT NULL,
    reviewed_at timestamptz NOT NULL,
    decision_id bigint NOT NULL REFERENCES decisions(id) DEFERRABLE INITIALLY DEFERRED,
    reviewer_id bigint REFERENCES core_customuser(id) DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX IF NOT EXISTS decision_reviews_decision_idx
    ON decision_reviews(decision_id)
    WHERE is_deleted = false;

CREATE TABLE IF NOT EXISTS decision_topic_labels (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    is_deleted boolean NOT NULL,
    topic varchar(64) NOT NULL,
    title varchar(80) NOT NULL,
    project_id bigint NOT NULL REFERENCES core_project(id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT unique_project_decision_topic_label UNIQUE (project_id, topic)
);

CREATE TABLE IF NOT EXISTS decision_state_transitions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    is_deleted boolean NOT NULL,
    from_status varchar(20) NOT NULL,
    to_status varchar(20) NOT NULL,
    transition_method varchar(50) NOT NULL,
    metadata jsonb,
    "timestamp" timestamptz NOT NULL,
    note text,
    decision_id bigint NOT NULL REFERENCES decisions(id) DEFERRABLE INITIALLY DEFERRED,
    triggered_by_id bigint REFERENCES core_customuser(id) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS meetings_meetingdecisionorigin (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origin_timestamp timestamptz NOT NULL,
    creation_context jsonb NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    created_by_id bigint NOT NULL REFERENCES core_customuser(id) DEFERRABLE INITIALLY DEFERRED,
    decision_id bigint NOT NULL REFERENCES decisions(id) DEFERRABLE INITIALLY DEFERRED,
    meeting_id bigint NOT NULL REFERENCES meetings_meeting(id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT meetings_meetingdecisionorigin_decision_id_key UNIQUE (decision_id),
    CONSTRAINT mtgs_dcor_unique_meeting_decision UNIQUE (meeting_id, decision_id)
);

CREATE TABLE IF NOT EXISTS decision_commit_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    is_deleted boolean NOT NULL,
    committed_at timestamptz NOT NULL,
    validation_snapshot jsonb,
    committed_by_id bigint REFERENCES core_customuser(id) DEFERRABLE INITIALLY DEFERRED,
    decision_id bigint NOT NULL REFERENCES decisions(id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT decision_commit_records_decision_id_key UNIQUE (decision_id)
);