            (1, {ConfiguredProjectId}, 'decisions', 'signal_metric', 'ROAS', false),
            (1, {ConfiguredProjectId}, 'decisions', 'signal_period', 'LAST_30_DAYS', false),
            (2, {ConfiguredProjectId}, 'decisions', 'signal_metric', 'CPA', false),
            (1, {ProjectId}, 'decisions', 'signal_metric', 'CPM', false)
