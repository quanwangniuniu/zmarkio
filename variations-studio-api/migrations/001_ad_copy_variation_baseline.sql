    target_table oid := to_regclass(format('%I.ad_copy_variation_adcopyvariation', tenant_schema));
    definitions text[];
BEGIN
    IF target_table IS NULL THEN
        CREATE TABLE ad_copy_variation_adcopyvariation (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            slug varchar(255) NOT NULL UNIQUE,
            created_at timestamptz NOT NULL,
            updated_at timestamptz NOT NULL,
            is_deleted boolean NOT NULL,
            project_id bigint,
            creative_id bigint,
            source_mode varchar(32) NOT NULL,
            source_ref text NOT NULL,
            hook text NOT NULL,
            headline text NOT NULL,
            description text NOT NULL,
            cta varchar(64) NOT NULL,
            instruction text NOT NULL,
            model_name varchar(64) NOT NULL,
            prompt_version varchar(32) NOT NULL,
            batch_id uuid,
            batch_position integer,
            status varchar(20) NOT NULL,
            created_by_id bigint,
            CONSTRAINT ad_copy_variation_adcopyvariation_batch_position_check CHECK (batch_position >= 0),
            CONSTRAINT ad_copy_variation_ad_project_id_abef521f_fk_core_proj
                FOREIGN KEY (project_id) REFERENCES core_project(id) DEFERRABLE INITIALLY DEFERRED,
            CONSTRAINT ad_copy_variation_ad_creative_id_7322bde4_fk_meta_ad_c
                FOREIGN KEY (creative_id) REFERENCES public.meta_ad_creatives(id) DEFERRABLE INITIALLY DEFERRED,
            CONSTRAINT ad_copy_variation_ad_created_by_id_2b000528_fk_core_cust
                FOREIGN KEY (created_by_id) REFERENCES public.core_customuser(id) DEFERRABLE INITIALLY DEFERRED
        );
        CREATE INDEX ad_copy_var_project_5f6c42_idx
            ON ad_copy_variation_adcopyvariation (project_id, status, created_at DESC);
        CREATE INDEX ad_copy_var_project_ef5425_idx
            ON ad_copy_variation_adcopyvariation (project_id, batch_id, status);
        CREATE INDEX ad_copy_var_creativ_ae4311_idx
            ON ad_copy_variation_adcopyvariation (creative_id, status, created_at DESC);
        CREATE INDEX ad_copy_variation_adcopyvariation_batch_id_84f1268d
            ON ad_copy_variation_adcopyvariation (batch_id);
        CREATE INDEX ad_copy_variation_adcopyvariation_status_0b69aad8
            ON ad_copy_variation_adcopyvariation (status);
        CREATE INDEX ad_copy_variation_adcopyvariation_status_0b69aad8_like
            ON ad_copy_variation_adcopyvariation (status varchar_pattern_ops);
        CREATE INDEX ad_copy_variation_adcopyvariation_slug_bbf68595_like
            ON ad_copy_variation_adcopyvariation (slug varchar_pattern_ops);
        CREATE INDEX ad_copy_variation_adcopyvariation_project_id_abef521f
            ON ad_copy_variation_adcopyvariation (project_id);
        CREATE INDEX ad_copy_variation_adcopyvariation_creative_id_7322bde4
            ON ad_copy_variation_adcopyvariation (creative_id);
        CREATE INDEX ad_copy_variation_adcopyvariation_created_by_id_2b000528
            ON ad_copy_variation_adcopyvariation (created_by_id);
    ELSE
        -- Verify existing tables before the runner records this baseline.
        IF NOT EXISTS (
            SELECT 1 FROM pg_catalog.pg_class
            WHERE oid = target_table AND relkind = 'r' AND relpersistence = 'p'
        ) THEN
            RAISE EXCEPTION 'Baseline mismatch in %: expected a permanent variation table', tenant_schema;
        END IF;

        IF EXISTS (
            WITH expected(position, name, type, not_null, identity) AS (VALUES
                (1, 'id', 'bigint', true, 'd'),
                (2, 'slug', 'character varying(255)', true, ''),
                (3, 'created_at', 'timestamp with time zone', true, ''),
                (4, 'updated_at', 'timestamp with time zone', true, ''),
                (5, 'is_deleted', 'boolean', true, ''),
                (6, 'project_id', 'bigint', false, ''),
                (7, 'creative_id', 'bigint', false, ''),
                (8, 'source_mode', 'character varying(32)', true, ''),
                (9, 'source_ref', 'text', true, ''),
                (10, 'hook', 'text', true, ''),
                (11, 'headline', 'text', true, ''),
                (12, 'description', 'text', true, ''),
                (13, 'cta', 'character varying(64)', true, ''),
                (14, 'instruction', 'text', true, ''),
                (15, 'model_name', 'character varying(64)', true, ''),
                (16, 'prompt_version', 'character varying(32)', true, ''),
                (17, 'batch_id', 'uuid', false, ''),
                (18, 'batch_position', 'integer', false, ''),
                (19, 'status', 'character varying(20)', true, ''),
                (20, 'created_by_id', 'bigint', false, '')
            ), actual AS (
                SELECT a.*, t.typcollation
                FROM pg_catalog.pg_attribute a
                JOIN pg_catalog.pg_type t ON t.oid = a.atttypid
                WHERE a.attrelid = target_table AND a.attnum > 0 AND NOT a.attisdropped
            )
            SELECT 1 FROM expected e FULL JOIN actual a ON a.attname = e.name
            WHERE e.name IS NULL OR a.attname IS NULL OR a.attnum <> e.position
               OR pg_catalog.format_type(a.atttypid, a.atttypmod) <> e.type
               OR a.attnotnull <> e.not_null OR a.attidentity::text <> e.identity
               OR a.atthasdef OR a.attgenerated <> '' OR a.attcollation <> a.typcollation
        ) THEN
            RAISE EXCEPTION 'Baseline mismatch in %: variation columns, defaults or identity differ', tenant_schema;
        END IF;

        -- Normalize only this tenant's qualification; public FK targets stay explicit.
        -- NOT NULL definitions are checked above; validation below covers all constraints.
        SELECT array_agg(c.conname || ': ' || replace(pg_catalog.pg_get_constraintdef(c.oid),
                             format('%I.', tenant_schema), '') ORDER BY c.conname)
        INTO definitions
        FROM pg_catalog.pg_constraint c WHERE c.conrelid = target_table AND c.contype <> 'n';
        IF definitions IS DISTINCT FROM ARRAY[
            'ad_copy_variation_ad_created_by_id_2b000528_fk_core_cust: FOREIGN KEY (created_by_id) REFERENCES public.core_customuser(id) DEFERRABLE INITIALLY DEFERRED',
            'ad_copy_variation_ad_creative_id_7322bde4_fk_meta_ad_c: FOREIGN KEY (creative_id) REFERENCES public.meta_ad_creatives(id) DEFERRABLE INITIALLY DEFERRED',
            'ad_copy_variation_ad_project_id_abef521f_fk_core_proj: FOREIGN KEY (project_id) REFERENCES core_project(id) DEFERRABLE INITIALLY DEFERRED',
            'ad_copy_variation_adcopyvariation_batch_position_check: CHECK ((batch_position >= 0))',
            'ad_copy_variation_adcopyvariation_pkey: PRIMARY KEY (id)',
            'ad_copy_variation_adcopyvariation_slug_key: UNIQUE (slug)'
        ] OR EXISTS (
            SELECT 1 FROM pg_catalog.pg_constraint WHERE conrelid = target_table AND NOT convalidated
        ) THEN
            RAISE EXCEPTION 'Baseline mismatch in %: variation primary/slug/check/foreign-key constraints differ', tenant_schema;
        END IF;

        SELECT array_agg(replace(pg_catalog.pg_get_indexdef(i.indexrelid),
                             format('%I.', tenant_schema), '') ORDER BY c.relname)
        INTO definitions
        FROM pg_catalog.pg_index i
        JOIN pg_catalog.pg_class c ON c.oid = i.indexrelid
        WHERE i.indrelid = target_table;
        IF definitions IS DISTINCT FROM ARRAY[
            'CREATE INDEX ad_copy_var_creativ_ae4311_idx ON ad_copy_variation_adcopyvariation USING btree (creative_id, status, created_at DESC)',
            'CREATE INDEX ad_copy_var_project_5f6c42_idx ON ad_copy_variation_adcopyvariation USING btree (project_id, status, created_at DESC)',
            'CREATE INDEX ad_copy_var_project_ef5425_idx ON ad_copy_variation_adcopyvariation USING btree (project_id, batch_id, status)',
            'CREATE INDEX ad_copy_variation_adcopyvariation_batch_id_84f1268d ON ad_copy_variation_adcopyvariation USING btree (batch_id)',
            'CREATE INDEX ad_copy_variation_adcopyvariation_created_by_id_2b000528 ON ad_copy_variation_adcopyvariation USING btree (created_by_id)',
            'CREATE INDEX ad_copy_variation_adcopyvariation_creative_id_7322bde4 ON ad_copy_variation_adcopyvariation USING btree (creative_id)',
            'CREATE UNIQUE INDEX ad_copy_variation_adcopyvariation_pkey ON ad_copy_variation_adcopyvariation USING btree (id)',
            'CREATE INDEX ad_copy_variation_adcopyvariation_project_id_abef521f ON ad_copy_variation_adcopyvariation USING btree (project_id)',
            'CREATE INDEX ad_copy_variation_adcopyvariation_slug_bbf68595_like ON ad_copy_variation_adcopyvariation USING btree (slug varchar_pattern_ops)',
            'CREATE UNIQUE INDEX ad_copy_variation_adcopyvariation_slug_key ON ad_copy_variation_adcopyvariation USING btree (slug)',
            'CREATE INDEX ad_copy_variation_adcopyvariation_status_0b69aad8 ON ad_copy_variation_adcopyvariation USING btree (status)',
            'CREATE INDEX ad_copy_variation_adcopyvariation_status_0b69aad8_like ON ad_copy_variation_adcopyvariation USING btree (status varchar_pattern_ops)'
        ] OR EXISTS (
            SELECT 1 FROM pg_catalog.pg_index
            WHERE indrelid = target_table AND (NOT indisvalid OR NOT indisready)
        ) THEN
            RAISE EXCEPTION 'Baseline mismatch in %: variation indexes differ or are not ready', tenant_schema;
        END IF;

        -- Resolve the identity sequence by ownership, allowing a different name or cache.
        -- Keep START 1 so RESTART IDENTITY retains Django's reset behaviour.
        IF NOT EXISTS (
            SELECT 1 FROM pg_catalog.pg_sequence s
            JOIN pg_catalog.pg_depend d ON d.objid = s.seqrelid AND d.classid = 'pg_catalog.pg_class'::regclass
            WHERE d.refclassid = 'pg_catalog.pg_class'::regclass
              AND d.refobjid = target_table AND d.refobjsubid = 1 AND d.deptype = 'i'
              AND s.seqtypid = 'bigint'::regtype AND s.seqstart = 1 AND s.seqincrement = 1
              AND s.seqmin = 1 AND s.seqmax = 9223372036854775807 AND NOT s.seqcycle
        ) THEN
            RAISE EXCEPTION 'Baseline mismatch in %: variation identity sequence or ownership differs', tenant_schema;
        END IF;
    END IF;
END
